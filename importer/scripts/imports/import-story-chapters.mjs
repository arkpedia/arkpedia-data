#!/usr/bin/env node
/**
 * data/story-library.json and data/story-chapters.json: every reader group, section by section, with the
 * place Timo's story reader gives that section, so the page's chapter popup opens one section
 * (its Before or its After) instead of the chapter's start. From the reader's own catalogue,
 * read as data (scripts/lib/timo-library.mjs: its code never runs here), independently of the map.
 * A run that cannot read the catalogue, or finds far too
 * few chapters, fails, and the stage keeps yesterday's file.
 *
 *   node scripts/imports/import-story-chapters.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { timoLibrary } from '../lib/timo-library.mjs';

export const CATALOG = 'https://arknights.timo.beer/json/catalog.en.json';
const OUT = path.join(process.cwd(), 'data', 'story-chapters.json');

let catalog;
try {
  if (process.env.ARKPEDIA_STORY_CATALOG) catalog = JSON.parse(fs.readFileSync(process.env.ARKPEDIA_STORY_CATALOG, 'utf8'));
  else {
  const response = await fetch(CATALOG, { headers: { 'User-Agent': 'ArkpediaBot/1.0 (+https://www.arkpedia.net)' }, signal: AbortSignal.timeout(90_000) });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  catalog = await response.json();
  }
} catch (error) {
  console.error(`import-story-chapters: Timo's catalogue could not be read (${error instanceof Error ? error.message : error}); yesterday's chapters stay.`);
  process.exit(1);
}

const { entries, chapters } = timoLibrary(catalog);
// Reject a partial response before either output changes. Never let a failed refresh erase the library.
if (entries.length < 400 || ['main', 'side', 'mini', 'record', 'module', 'rogue', 'sandbox', 'extra'].some(category => !entries.some(entry => entry.category === category))) throw new Error('Incomplete reader catalogue; previous library stays.');
const text = `${JSON.stringify({ about: 'Every reader chapter, independent of canvas membership: [index, code, name, tag]. Generated by scripts/imports/import-story-chapters.mjs.', source: CATALOG, completeLibrary: true, chapters })}\n`;
if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) fs.writeFileSync(OUT, text);
const library = path.join(process.cwd(), 'data', 'story-library.json');
fs.writeFileSync(library, `${JSON.stringify({ source: CATALOG, entries })}\n`);
console.log(`Wrote story library: ${entries.length} groups, ${Object.keys(chapters).length} chapters with sections.`);

