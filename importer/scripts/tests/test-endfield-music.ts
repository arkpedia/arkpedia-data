/** A YouTube art-track thumbnail, which the site draws an album from until its cover is published. */
const YOUTUBE_COVER = /^https:\/\/i\.ytimg\.com\/vi\/[\w-]{11}\/(?:maxres|hq)default\.jpg$/;

const DESCRIPTION = `Provided to YouTube by YOYOROCK

Test Song · Metal Scar Radio · Composer One · Singer Two

Test Album Original Soundtrack

℗ GRYPHLINE

Released on: 2026-10-19

Producer: Composer One
Composer: Composer One
Lyricist: Writer Three
Associated  Performer: Singer Two

Auto-generated by YouTube.`;

test('an auto-generated upload\'s description gives the song, its album, artists, credits and day', () => {
  assert.deepEqual(parseDescription(DESCRIPTION), {
    title: 'Test Song',
    artists: ['Metal Scar Radio', 'Composer One', 'Singer Two'],
    album: 'Test Album Original Soundtrack',
    label: 'GRYPHLINE',
    releaseDate: '2026/10/19',
    credits: [
      { role: 'producer', names: ['Composer One'] },
      { role: 'composer', names: ['Composer One'] },
      { role: 'lyrics', names: ['Writer Three'] },
    ],
  });
  assert.equal(parseDescription('A trailer for the new version.\n\nWatch now!'), null, 'only a distributor\'s upload is read');
  assert.equal(parseDescription(''), null);
});

/** One playlist row as YouTube draws it: a video lockup, its channel in the byline. */
const lockup = (videoId: string, title: string, channel: string, duration = '3:35') => ({
  lockupViewModel: {
    contentId: videoId,
    contentType: 'LOCKUP_CONTENT_TYPE_VIDEO',
    contentImage: { thumbnailViewModel: { overlays: [{ thumbnailBottomOverlayViewModel: { badges: [{ thumbnailBadgeViewModel: { text: duration } }] } }] } },
    metadata: { lockupMetadataViewModel: { title: { content: title }, metadata: { contentMetadataViewModel: { metadataRows: [{ metadataParts: [
      { text: { content: 'Someone - Topic', commandRuns: [{ onTap: { innertubeCommand: { browseEndpoint: { browseId: channel } } } }] } },
    ] }] } } } },
  },
});

test('an album playlist gives the label\'s own uploads in order, never a stand-in from another channel', () => {
  const page = { contents: { list: [
    lockup('aaaaaaaaaa1', 'First', CHANNEL, '3:35'),
    // Where the label's upload is missing YouTube shows someone else's (2026-10: a fan's re-upload).
    lockup('fanupload01', '【Fan】 boss theme re-upload', 'UCsomeoneElse000000000000'),
    lockup('aaaaaaaaaa2', 'Second', CHANNEL, '1:02:03'),
  ] } };
  assert.deepEqual(parsePlaylist(page), [
    { videoId: 'aaaaaaaaaa1', title: 'First', length: '03:35' },
    { videoId: 'aaaaaaaaaa2', title: 'Second', length: '62:03' },
  ]);
});

test('the Albums & Singles list gives each album\'s playlist, name, song count and day', () => {
  const grid = (playlistId: string, title: string, count: string, day: string) => ({ gridPlaylistRenderer: {
    playlistId, title: { runs: [{ text: title }] }, videoCountText: { runs: [{ text: count }, { text: ' videos' }] },
    shortBylineText: { runs: [{ text: 'Metal Scar Radio' }, { text: ' · ' }, { text: day }] },
  } });
  assert.deepEqual(parseReleases({ items: [grid('OLAK5uy_one', 'Album One', '26', 'Oct 19, 2026'), grid('OLAK5uy_two', 'Single', '1', 'Apr 21, 2026'), grid('PLnotAnAlbum', 'A playlist', '3', 'Jan 1, 2026')] }), [
    { playlistId: 'OLAK5uy_one', name: 'Album One', count: 26, releaseDate: '2026/10/19' },
    { playlistId: 'OLAK5uy_two', name: 'Single', count: 1, releaseDate: '2026/04/21' },
  ]);
});

const DETAILS = parseDescription(DESCRIPTION);
const describe = (title: string, album: string) => parseDescription(DESCRIPTION.replace('Test Song', title).replace('Test Album Original Soundtrack', album));

test('the merge adds albums and songs marked Endfield, with ids no Monster Siren gate takes', () => {
  const release = { playlistId: 'OLAK5uy_one', name: 'Test Album Original Soundtrack', count: 2, releaseDate: '2026/10/19' };
  const { albums, added, partial } = mergeEndfield({
    albums: [],
    releases: [release],
    playlists: [{ release, songs: [{ videoId: 'aaaaaaaaaa1', title: 'Test Song', length: '03:35' }, { videoId: 'aaaaaaaaaa2', title: 'Other', length: '' }] }],
    descriptions: new Map([['aaaaaaaaaa1', DETAILS]]),
  });
  assert.deepEqual(added, { albums: 1, songs: 2 });
  const [album] = albums;
  assert.equal(album.game, 'endfield');
  assert.equal(album.albumId, 'endfield-test-album-original-soundtrack');
  assert.equal(album.youtubePlaylistId, 'OLAK5uy_one');
  assert.equal(album.releaseDate, '2026/10/19');
  assert.deepEqual(album.songs.map((song: { songId: string }) => song.songId), ['endfield-aaaaaaaaaa1', 'endfield-aaaaaaaaaa2']);
  // The label is an artist only where no one else is credited, as Monster Siren's records credit it.
  assert.deepEqual(album.songs[0].credits[0], { role: 'artist', names: ['Composer One', 'Singer Two'] });
  assert.equal(album.songs[0].copyright, 'no');
  // The song its description was not read for is flagged, and the album is complete.
  assert.deepEqual(partial, [{ key: 'song:aaaaaaaaaa2', reason: 'added without credits: its YouTube description was not read' }]);
  assert.ok(!LABEL_ARTIST.includes('·'));
});

test('the merge fills in what is missing and rewrites nothing a person wrote', () => {
  const release = { playlistId: 'OLAK5uy_one', name: 'Test Album Original Soundtrack', count: 3, releaseDate: '2026/10/19' };
  const first = mergeEndfield({ albums: [], releases: [release], playlists: [{ release, songs: [{ videoId: 'aaaaaaaaaa1', title: 'Test Song', length: '' }] }] }).albums;
  first[0].albumAltName = 'Edited by hand';
  first[0].songs[0].songAltName = 'Translated';
  const second = mergeEndfield({
    albums: first,
    releases: [release],
    playlists: [{ release, songs: [{ videoId: 'aaaaaaaaaa0', title: 'Opening', length: '01:00' }, { videoId: 'aaaaaaaaaa1', title: 'Renamed upstream', length: '03:35' }] }],
    descriptions: new Map([['aaaaaaaaaa1', DETAILS]]),
  });
  const [album] = second.albums;
  assert.equal(album.albumAltName, 'Edited by hand');
  assert.deepEqual(album.songs.map((song: { videoId: string }) => song.videoId), ['aaaaaaaaaa0', 'aaaaaaaaaa1'], 'the playlist\'s order');
  const kept = album.songs[1];
  assert.equal(kept.songName, 'Test Song', 'a title already written stays');
  assert.equal(kept.songAltName, 'Translated');
  assert.equal(kept.length, '03:35', 'a length is filled in once read');
  assert.equal(kept.credits[0].role, 'artist', 'credits are filled in once read');
  // Read tonight, the playlist's own songs are the measure: both are in, so it is complete.
  assert.ok(!second.partial.some((entry: { key: string }) => entry.key === `album:${album.albumId}`));
  // Not read (YouTube refused it), the list's count is: two of three, short.
  const unread = mergeEndfield({ albums: second.albums, releases: [release] });
  assert.deepEqual(unread.partial.filter((entry: { key: string }) => entry.key.startsWith('album:')),
    [{ key: `album:${album.albumId}`, reason: 'its YouTube album lists 3 songs and the catalogue has 2' }]);
  assert.deepEqual(first[0].songs.length, 1, 'the input is not changed');
});

test('a playlist with none of the label\'s uploads makes no album', () => {
  const release = { playlistId: 'OLAK5uy_empty', name: 'Only stand-ins', count: 1, releaseDate: '2026/10/19' };
  const { albums, partial } = mergeEndfield({ albums: [], releases: [release], playlists: [{ release, songs: [] }] });
  assert.deepEqual(albums, []);
  assert.deepEqual(partial, []);
});

test('a song only the feed carries makes its album from the description', () => {
  const { albums } = mergeEndfield({
    albums: [],
    feed: [
      { videoId: 'bbbbbbbbbb2', title: 'Newer', details: describe('Newer', 'A New Single') },
      { videoId: 'bbbbbbbbbb1', title: 'Older', details: describe('Older', 'A New Single') },
      { videoId: 'notlabel001', title: 'A trailer', details: null },
    ],
  });
  assert.equal(albums.length, 1);
  assert.equal(albums[0].albumName, 'A New Single');
  assert.equal(albums[0].releaseDate, '2026/10/19');
  assert.deepEqual(albums[0].songs.map((song: { songName: string }) => song.songName), ['Older', 'Newer'], 'oldest first');
});

/** A fetcher standing in for YouTube: the feed, or nothing. */
function fakeYouTube({ feed }: { feed: string | null }) {
  return async (url: string, init?: RequestInit) => {
    if (url === FEED) return feed === null ? new Response('', { status: 500 }) : new Response(feed);
    if (init?.method === 'HEAD') return new Response(null, { status: 200 });
    return new Response('', { status: 429 });
  };
}

const FEED_XML = `<?xml version="1.0" encoding="UTF-8"?><feed xmlns:yt="http://www.youtube.com/xml/schemas/2015" xmlns:media="http://search.yahoo.com/mrss/">
 <entry><yt:videoId>ccccccccccc</yt:videoId><title>Test Song</title><published>2026-10-19T10:39:21+00:00</published>
  <link rel="alternate" href="https://www.youtube.com/watch?v=ccccccccccc"/>
  <media:group><media:description>${DESCRIPTION.replace(/&/g, '&amp;')}</media:description></media:group></entry>
</feed>`;

test('a night\'s run writes the file, reports what it could not read, and a second run changes nothing', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'endfield-'));
  fs.mkdirSync(path.join(root, 'data'));
  fs.writeFileSync(path.join(root, 'data/quarantine.json'), '{"version":1,"entries":[]}\n');
  const log = () => {};
  const now = new Date('2026-10-22T00:00:00Z');
  await syncEndfieldAlbums({ root, fetcher: fakeYouTube({ feed: FEED_XML }), now, log });
  const file = fs.readFileSync(path.join(root, 'data/endfield-albums.json'), 'utf8');
  const albums = JSON.parse(file);
  assert.equal(albums.length, 1);
  assert.equal(albums[0].songs[0].videoId, 'ccccccccccc');
  assert.match(albums[0].coverUrl, YOUTUBE_COVER);
  // The album list was refused (429): reported, and the feed's song still went in. Its cover is
  // drawn from YouTube until one is published (test-endfield-covers.ts).
  assert.deepEqual(readQuarantine(root).entries.map((entry: { key: string; action: string }) => [entry.key, entry.action]),
    [['cover:endfield-test-album-original-soundtrack', 'published-partial'], ['endfield:albums', 'kept-previous']]);

  await syncEndfieldAlbums({ root, fetcher: fakeYouTube({ feed: null }), now, log });
  assert.equal(fs.readFileSync(path.join(root, 'data/endfield-albums.json'), 'utf8'), file, 'nothing read, nothing lost');
  assert.deepEqual(readQuarantine(root).entries.map((entry: { key: string }) => entry.key), ['cover:endfield-test-album-original-soundtrack', 'endfield:albums', 'endfield:feed']);
  fs.rmSync(root, { recursive: true, force: true });
});

